/* Sculpted route tiles. Each context owns a small, lazily painted atlas; create it
   once per board before rendering, and merge meshes sharing material afterwards. */
(function(global){
  'use strict';
  var SIZE = 1024, CELL = 128, COLS = 8, PAD = 4, TAU = Math.PI * 2;
  function shade(hex, amount){
    var c = new global.THREE.Color(hex), h = {}; c.getHSL(h);
    c.setHSL(h.h, h.s, Math.max(0, Math.min(1, h.l + amount)));
    return '#' + c.getHexString();
  }
  function rand(n){ var x = Math.sin(n * 127.1 + 311.7) * 43758.5453; return x - Math.floor(x); }
  function circle(g, x, y, r){ g.beginPath(); g.arc(x, y, r, 0, TAU); }
  function paintStone(g, x, y, image, night, region){
    g.save(); g.beginPath(); g.rect(x, y, CELL, CELL); g.clip();
    g.fillStyle = night ? '#a8b6bb' : '#f4e7cb'; g.fillRect(x, y, CELL, CELL);
    if(image && (image.complete === undefined || image.complete) && (image.naturalWidth === undefined || image.naturalWidth)){
      try { g.globalAlpha = .52; g.drawImage(image, x, y, CELL, CELL); g.globalAlpha = 1; } catch(e){}
    }
    // Fine, low-contrast grains are painted once, not generated by a shader.
    for(var i = 0; i < 490; i++){
      var px = x + rand(i * 3 + 1) * CELL, py = y + rand(i * 3 + 2) * CELL;
      g.fillStyle = i % 3 ? 'rgba(111,94,73,.075)' : 'rgba(255,255,244,.22)';
      g.fillRect(px, py, i % 7 === 0 ? 2 : 1, 1);
    }
    var wood = region === 'captain' || region === 'town';
    g.strokeStyle = wood ? 'rgba(121,91,67,.12)' : 'rgba(141,115,87,.09)'; g.lineWidth = .7;
    for(var j = 0; j < 9; j++){
      var yy = y + 8 + j * 14;
      g.beginPath(); g.moveTo(x - 4, yy); g.bezierCurveTo(x + 32, yy - 4, x + 78, yy + 5, x + 132, yy - 2); g.stroke();
    }
    // Sparse little paired pores catch light at the edge of the stone.
    for(var pore = 0; pore < 32; pore++){
      var sx = x + 4 + rand(pore * 8 + 11) * 120, sy = y + 4 + rand(pore * 8 + 12) * 120;
      g.fillStyle = 'rgba(104,84,68,.11)'; circle(g, sx, sy, .65); g.fill();
      g.fillStyle = 'rgba(255,251,230,.25)'; g.fillRect(sx, sy + 1, 1.3, .55);
    }
    g.restore();
  }
  function paintFace(g, x, y, col, icon, night, kind, style, region, image){
    g.save(); g.translate(x, y);
    var bg = g.createRadialGradient(48, 41, 4, 64, 64, 73);
    bg.addColorStop(0, shade(col, .12)); bg.addColorStop(.72, col); bg.addColorStop(1, shade(col, -.12));
    g.fillStyle = bg; g.fillRect(0, 0, CELL, CELL);
    // Blend the photographed shellstone into the pigment while retaining each
    // space's distinct color. Icons and inset outlines are painted afterwards.
    if(image && (image.complete === undefined || image.complete) && (image.naturalWidth === undefined || image.naturalWidth)){
      try {
        g.save(); g.globalAlpha = .42; g.globalCompositeOperation = 'multiply';
        g.drawImage(image, 0, 0, CELL, CELL); g.restore();
      } catch(e) { g.restore(); }
    }
    for(var i = 0; i < 190; i++){
      g.fillStyle = i % 2 ? 'rgba(255,255,255,.12)' : 'rgba(94,77,58,.055)';
      g.fillRect(rand(i * 4 + 7) * 128, rand(i * 4 + 8) * 128, 1, 1);
    }
    // An inset shadow and highlight make the painted center feel set into stone.
    circle(g, 64, 65, 55); g.strokeStyle = 'rgba(75,62,49,.24)'; g.lineWidth = 5; g.stroke();
    circle(g, 64, 63, 53); g.strokeStyle = 'rgba(255,252,232,.48)'; g.lineWidth = 2; g.stroke();
    // Broken, fine incisions sit just inside the worn lip. A small offset
    // highlight gives each cut a carved edge without another layer of geometry.
    for(var cut = 0; cut < 18; cut++){
      var ca = cut * TAU / 18 + .045, cr = 50.5, cx = 64 + Math.cos(ca) * cr, cy = 64 + Math.sin(ca) * cr;
      var tx = -Math.sin(ca) * 1.4, ty = Math.cos(ca) * 1.4;
      g.lineWidth = .65; g.strokeStyle = 'rgba(91,70,57,.22)';
      g.beginPath(); g.moveTo(cx - tx, cy - ty); g.lineTo(cx + tx, cy + ty); g.stroke();
      g.strokeStyle = 'rgba(255,252,231,.30)';
      g.beginPath(); g.moveTo(cx - tx, cy - ty + .8); g.lineTo(cx + tx, cy + ty + .8); g.stroke();
    }
    if(style === 'shell'){
      for(var j = 0; j < 12; j++){
        var a = j * TAU / 12;
        g.strokeStyle = 'rgba(255,255,240,.30)'; g.lineWidth = 2;
        g.beginPath(); g.moveTo(64 + Math.cos(a) * 40, 64 + Math.sin(a) * 40); g.lineTo(64 + Math.cos(a) * 51, 64 + Math.sin(a) * 51); g.stroke();
        g.strokeStyle = 'rgba(94,76,62,.14)'; g.lineWidth = .7;
        g.beginPath(); g.moveTo(65 + Math.cos(a) * 41, 64 + Math.sin(a) * 41); g.lineTo(65 + Math.cos(a) * 50, 64 + Math.sin(a) * 50); g.stroke();
      }
    } else {
      g.strokeStyle = kind.indexOf('deck') === 0 ? (night ? '#d8ab52' : '#e6b64f') : 'rgba(255,255,247,.64)';
      g.lineWidth = kind.indexOf('deck') === 0 ? 4 : 2; g.setLineDash(kind === 'plain' ? [] : [8, 6]);
      circle(g, 64, 64, 47); g.stroke(); g.setLineDash([]);
    }
    if(kind.indexOf('deck') === 0 || (style === 'shell' && !icon)){
      var insetR = kind.indexOf('deck') === 0 ? 37 : 25;
      g.fillStyle = night ? '#ded7be' : '#fffbea'; circle(g, 64, 64, insetR); g.fill();
      if(image && (image.complete === undefined || image.complete) && (image.naturalWidth === undefined || image.naturalWidth)){
        try {
          g.save(); circle(g, 64, 64, insetR); g.clip();
          g.globalAlpha = .58; g.globalCompositeOperation = 'multiply'; g.drawImage(image, 0, 0, CELL, CELL); g.restore();
        } catch(e) { g.restore(); }
      }
      // A fine shaded seam separates the inset from its surrounding pigment.
      circle(g, 64, 64, insetR - .6); g.lineWidth = 1;
      g.strokeStyle = 'rgba(104,84,64,.22)'; g.stroke();
      g.beginPath(); g.arc(64, 64, insetR - 2, Math.PI * 1.08, Math.PI * 1.9);
      g.strokeStyle = 'rgba(255,255,241,.55)'; g.stroke();
    }
    g.textAlign = 'center'; g.textBaseline = 'middle';
    if(icon === '?' || icon === '!'){
      g.fillStyle = night ? '#ffe29a' : '#fffdf3'; g.font = '900 71px system-ui, sans-serif'; g.fillText(icon, 64, 68);
    } else if(icon){
      g.fillStyle = night ? '#694a20' : '#155664';
      g.font = /[가-힣]/.test(icon) ? '700 54px system-ui, sans-serif' : (style === 'shell' ? '52px' : '62px') + ' "Apple Color Emoji","Segoe UI Emoji","Noto Color Emoji",sans-serif';
      g.fillText(icon, 64, 67);
    } else {
      // A little etched shell instead of a blank dot.
      g.strokeStyle = night ? '#7a887c' : '#c7ac83'; g.lineWidth = 2; g.lineCap = 'round';
      for(var k = -2; k <= 2; k++){ g.beginPath(); g.moveTo(64, 77); g.quadraticCurveTo(64 + k * 6, 66, 64 + k * 8, 53); g.stroke(); }
      g.beginPath(); g.arc(64, 62, 17, Math.PI * 1.05, Math.PI * 1.95); g.stroke();
    }
    if(kind === 'deck-done'){
      g.font = '900 30px system-ui, sans-serif'; g.lineWidth = 3; g.strokeStyle = '#8a5a12'; g.fillStyle = '#ffcf3f'; g.strokeText('★', 100, 30); g.fillText('★', 100, 30);
    }
    g.restore();
  }
  function uvIn(slot, u, v){
    var x = slot % COLS, y = Math.floor(slot / COLS);
    return [(x * CELL + PAD + u * (CELL - PAD * 2)) / SIZE, 1 - (y * CELL + PAD + (1 - v) * (CELL - PAD * 2)) / SIZE];
  }
  function bodyGeometry(R, style, slot){
    var THREE = global.THREE, shell = style === 'shell', n = shell ? 32 : 40;
    // Five/six continuous bands include the rounded foot, worn bevel and recessed lip.
    var rings = shell ? [[1.02,0],[1.04,.055],[1.02,.20],[.97,.30],[.90,.325]] : [[1.04,0],[1.06,.045],[1.045,.14],[1.01,.25],[.97,.315],[.92,.335],[.90,.325]];
    var p = [], uv = [], colors = [], idx = [];
    for(var j = 0; j < rings.length; j++) for(var i = 0; i <= n; i++){
      var a = i / n * TAU;
      // Shallow scallops and a few asymmetrical chips, bounded so neighboring tiles remain clear.
      var scallop = shell ? .035 * Math.cos(a * 12) : .009 * Math.sin(a * 5 + .7);
      var chip = Math.pow(Math.max(0, Math.cos(a - 2.37)), 34) * .024 + Math.pow(Math.max(0, Math.cos(a - 5.04)), 42) * .018;
      var edgeWeight = j === 0 ? .4 : (j === rings.length - 1 ? .25 : 1);
      var r = R * rings[j][0] * (1 + edgeWeight * (scallop - chip));
      var xx = Math.cos(a) * r, zz = Math.sin(a) * r;
      p.push(xx, rings[j][1], zz);
      var t = uvIn(slot, i / n, rings[j][1] / .335); uv.push(t[0],t[1]);
      var level = [ .68, .76, .86, .94, 1, 1, .87 ][Math.min(j,6)] * (.97 + .03 * Math.cos(a - .8));
      colors.push(level,level,level);
    }
    for(var k = 0; k < rings.length - 1; k++) for(var q = 0; q < n; q++){
      var a0 = k * (n + 1) + q, b = a0 + 1, c = a0 + n + 1, d = c + 1;
      idx.push(a0,c,b,b,c,d);
    }
    var geo = new THREE.BufferGeometry();
    geo.setAttribute('position', new THREE.Float32BufferAttribute(p,3)); geo.setAttribute('uv', new THREE.Float32BufferAttribute(uv,2));
    geo.setAttribute('color', new THREE.Float32BufferAttribute(colors,3)); geo.setIndex(idx); geo.computeVertexNormals();
    return geo;
  }
  function faceGeometry(R, style, slot){
    var THREE = global.THREE, n = style === 'shell' ? 32 : 40, geo = new THREE.CircleGeometry(R * .901, n);
    geo.rotateX(-Math.PI / 2);
    var uv = geo.attributes.uv, color = [];
    for(var i = 0; i < uv.count; i++){
      var t = uvIn(slot, uv.getX(i), uv.getY(i)); uv.setXY(i,t[0],t[1]); color.push(1,1,1);
    }
    geo.setAttribute('color', new THREE.Float32BufferAttribute(color,3)); return geo;
  }
  function createContext(options){
    options = options || {}; var THREE = global.THREE, pages = [], variants = {}, region = options.region && (options.region.id || options.region) || '';
    function page(){
      var canvas = document.createElement('canvas'); canvas.width = canvas.height = SIZE;
      var g = canvas.getContext('2d'); paintStone(g,0,0,options.textureImage || global.REEF_TILE_SURFACE_IMAGE, !!options.night, region);
      var texture = new THREE.CanvasTexture(canvas); texture.anisotropy = 2;
      var material = new THREE.MeshBasicMaterial({ map:texture, vertexColors:true });
      var entry = { canvas:canvas, context:g, texture:texture, material:material, next:1 }; pages.push(entry); return entry;
    }
    function tile(style,s,R,top,icon,night,kit,M,mesh){
      var kind = s.kind === 'deck' ? 'deck-' + (s.item && s.item.state || '') : s.kind;
      var key = [style,top,icon,night,kind].join('|'), v = variants[key];
      if(!v){
        var pg = pages[pages.length-1]; if(!pg || pg.next >= 64) pg = page();
        var slot = pg.next++, x = (slot % COLS) * CELL, y = Math.floor(slot / COLS) * CELL;
        paintFace(pg.context,x,y,top,icon,night,kind,style,region,options.textureImage || global.REEF_TILE_SURFACE_IMAGE); pg.texture.needsUpdate = true;
        v = variants[key] = { page:pg, slot:slot };
      }
      var body = new THREE.Mesh(bodyGeometry(R,style,0),v.page.material); body.position.set(s.x,0,s.z);
      var face = new THREE.Mesh(faceGeometry(R,style,v.slot),v.page.material); face.position.set(s.x,.326,s.z);
      return { parts:[body], face:face };
    }
    return { tile:tile, atlases:pages };
  }
  var surfacePromise = null;
  function loadSurface(){
    if(global.REEF_TILE_SURFACE_IMAGE) return Promise.resolve(global.REEF_TILE_SURFACE_IMAGE);
    if(surfacePromise) return surfacePromise;
    surfacePromise = new Promise(function(resolve){
      var image = new Image(), settled = false;
      var timer = setTimeout(function(){ finish(null); }, 2000);
      function finish(result){
        if(settled) return;
        settled = true; clearTimeout(timer); image.onload = image.onerror = null;
        if(result) global.REEF_TILE_SURFACE_IMAGE = result;
        resolve(result);
      }
      image.onload = function(){ finish(image); };
      image.onerror = function(){ finish(null); };
      image.src = global.REEF_TILE_SURFACE_URL || 'assets/world/shellstone-color.jpg';
    });
    return surfacePromise;
  }
  global.ReefTileArt = { createContext:createContext, loadSurface:loadSurface };
})(window);
